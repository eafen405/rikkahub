package me.rerere.rikkahub.data.remote

import java.util.Base64
import javax.crypto.Cipher
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Where the signed-in account's session credential lives between runs.
 *
 * The credential is a bearer secret: whoever reads it can act as that account
 * until it is revoked. Implementations must therefore never persist it in the
 * clear, and must keep it out of anything a backup or a log would pick up.
 */
interface CredentialStore {
    suspend fun save(token: String)

    suspend fun load(): String?

    suspend fun clear()
}

/**
 * In-memory store for tests and previews.
 *
 * Deliberately not a persistence implementation: it forgets everything when the
 * process dies, which is the honest behaviour for anything that is not a real
 * key store.
 */
class InMemoryCredentialStore(initial: String? = null) : CredentialStore {
    private var token: String? = initial

    override suspend fun save(token: String) {
        this.token = token
    }

    override suspend fun load(): String? = token

    override suspend fun clear() {
        token = null
    }
}

/**
 * Packs an AES-GCM ciphertext with the nonce it was produced under.
 *
 * GCM needs a fresh nonce per message and must never reuse one under the same
 * key, so the nonce is generated by the cipher and stored alongside the body
 * rather than derived from anything. Authentication is GCM's own tag: a value
 * the app did not write fails to open instead of decrypting to garbage.
 *
 * Only `javax.crypto` is used here, so the envelope is exercised by ordinary
 * JVM unit tests; the platform-specific part is obtaining the key.
 */
object SealedSecret {
    private const val TRANSFORMATION = "AES/GCM/NoPadding"
    private const val TAG_BITS = 128
    private const val SEPARATOR = ':'

    /** @return `base64(nonce):base64(ciphertext + tag)`. */
    fun seal(key: SecretKey, plaintext: String): String {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, key)
        val body = cipher.doFinal(plaintext.toByteArray(Charsets.UTF_8))
        val encoder = Base64.getEncoder()
        return encoder.encodeToString(cipher.iv) + SEPARATOR + encoder.encodeToString(body)
    }

    /**
     * @throws javax.crypto.AEADBadTagException when the value was not produced
     *   by [seal] under this key, or was altered after it was written.
     */
    fun open(key: SecretKey, stored: String): String {
        val separator = stored.indexOf(SEPARATOR)
        require(separator > 0) { "the stored value carries no nonce" }
        val nonce = Base64.getDecoder().decode(stored.substring(0, separator))
        val body = Base64.getDecoder().decode(stored.substring(separator + 1))
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.DECRYPT_MODE, key, GCMParameterSpec(TAG_BITS, nonce))
        return String(cipher.doFinal(body), Charsets.UTF_8)
    }
}
